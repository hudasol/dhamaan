"""Build the generated documents from templates and facts.

Usage: python -m docsgen.build           write every document
       python -m docsgen.build --check   exit 1 if a committed document differs from what would be built
Templates live in docs/templates/*.tmpl.md and may contain digits only inside identifiers, code spans or
{{FACT}} placeholders (tests/test_docs.py enforces this). Every value comes from docsgen/facts.py.
"""
from __future__ import annotations

import argparse, os, re, sys

from docsgen import facts as F

ROOT = F.ROOT
OUTPUTS = {
    "README.md": "README.tmpl.md",
    "docs/ARCHITECTURE.md": "ARCHITECTURE.tmpl.md",
    "docs/CONTEXT.md": "CONTEXT.tmpl.md",
    "docs/METHOD.md": "METHOD.tmpl.md",
    "docs/EVALUATION.md": "EVALUATION.tmpl.md",
    "docs/EVALUATION_R2.md": "EVALUATION_R2.tmpl.md",
    "docs/LIMITATIONS.md": "LIMITATIONS.tmpl.md",
    "docs/PILOT.md": "PILOT.tmpl.md",
    "docs/SECURITY.md": "SECURITY.tmpl.md",
    "docs/DATA_STATEMENT.md": "DATA_STATEMENT.tmpl.md",
    "docs/VALIDATOR_WARNINGS.md": "VALIDATOR_WARNINGS.tmpl.md",
    "docs/PILOT_KIT/LOGGING_SPEC.md": "PILOT_KIT_LOGGING.tmpl.md",
    "docs/PILOT_KIT/WALKTHROUGH.md": "PILOT_KIT_WALKTHROUGH.tmpl.md",
    "docs/PROPOSAL/LIMITS_NOTE.md": "PROPOSAL_LIMITS.tmpl.md",
    "HANDOFF.md": "HANDOFF.tmpl.md",
    "docs/paper/manuscript.md": "MANUSCRIPT.tmpl.md",
}
BRIEF_TEMPLATE = "PROPOSAL_BRIEF.tmpl.md"   # rendered once per audience in data/proposal_pack.yaml
PLACEHOLDER = re.compile(r"\{\{([A-Z0-9_]+)\}\}")


def template_path(name: str) -> str:
    return os.path.join(ROOT, "docs", "templates", name)


def render(template: str, facts: dict, name: str = "") -> str:
    missing = sorted({k for k in PLACEHOLDER.findall(template) if k not in facts})
    if missing: raise KeyError(f"{name}: unknown facts {missing}")
    body = PLACEHOLDER.sub(lambda m: facts[m.group(1)], template)
    header = f"<!-- Generated by docsgen/build.py from docs/templates/{name}. Edit the template, not this file. -->\n"
    return header + body


def build(facts: dict | None = None) -> dict[str, str]:
    facts = facts if facts is not None else F.all_facts()
    out = {}
    for rel, tmpl in OUTPUTS.items():
        p = template_path(tmpl)
        if not os.path.exists(p): raise FileNotFoundError(f"template missing for {rel}: docs/templates/{tmpl}")
        out[rel] = render(open(p, encoding="utf-8").read(), facts, tmpl)
    brief = open(template_path(BRIEF_TEMPLATE), encoding="utf-8").read()
    for aud in audiences():
        extra = {"AUD_LABEL": aud["label"], "AUD_WHY": aud["why"], "AUD_ASK": aud["ask"],
                 "AUD_DELIVER": "\n".join(f"- {d}" for d in aud["deliver"])}
        out[f"docs/PROPOSAL/{aud['file']}"] = render(brief, facts | extra, BRIEF_TEMPLATE)
    return out


def audiences() -> list[dict]:
    import yaml
    return yaml.safe_load(open(os.path.join(ROOT, "data", "proposal_pack.yaml"), encoding="utf-8"))["audiences"]


def stale(built: dict[str, str] | None = None) -> list[str]:
    built = built if built is not None else build()
    bad = []
    for rel, text in built.items():
        p = os.path.join(ROOT, rel)
        if not os.path.exists(p) or open(p, encoding="utf-8", newline="").read() != text: bad.append(rel)
    return bad


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(); ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    built = build()
    if a.check:
        s = stale(built)
        for rel in s: print("STALE", rel)
        print(f"{len(s)} stale documents"); return 1 if s else 0
    for rel, text in built.items():
        os.makedirs(os.path.dirname(os.path.join(ROOT, rel)), exist_ok=True)
        with open(os.path.join(ROOT, rel), "w", encoding="utf-8", newline="\n") as f: f.write(text)
        print("wrote", rel)
    return 0


if __name__ == "__main__":
    sys.exit(main())
