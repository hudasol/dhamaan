def page(name: str, title: str, body: str, lang: str = "en", banner: str = BANNER, script: str = "") -> str:
    d = "rtl" if lang == "ar" else "ltr"
    nav = "".join(f'<li><a href="{h}"{" aria-current=page" if h == name else ""}{" lang=ar dir=rtl" if h == "ar.html" and lang != "ar" else ""}>{html.escape(t)}</a></li>'
                  for h, t in NAV)
    return (f'<!doctype html>\n<html lang="{lang}" dir="{d}"><head><meta charset="utf-8">'
            f'<meta name="viewport" content="width=device-width, initial-scale=1"><title>{html.escape(title)} | dhamaan</title>'
            f'<style>{CSS}</style></head><body><div class="banner" role="note">{html.escape(banner)}</div>'
            f'<header><h1>{html.escape(title)}</h1><nav aria-label="Pages"><ul>{nav}</ul></nav></header>'
            f'<main>{body}</main><footer>Generated by docsgen/site.py from the repository data. Proposed licences: MIT for code, '
            f'CC BY 4.0 for documents and data, pending the owner\'s confirmation.</footer>'
            + (f"<script>{script}</script>" if script else "") + "</body></html>\n")


def _csv(rel):
    return list(csv.DictReader(open(os.path.join(ROOT, rel), encoding="utf-8", newline="")))


def _md(rel):
    return to_html(open(os.path.join(ROOT, rel), encoding="utf-8").read())


