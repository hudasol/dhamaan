def build_site(facts: dict | None = None) -> dict[str, str]:
    f = facts if facts is not None else F.all_facts()
    return {
        "index.html": index_page(f), "evidence.html": evidence_page(f), "coverage.html": coverage_page(f), "case.html": case_page(f),
        "evaluation.html": md_page("evaluation.html", "Evaluation, first round", "docs/EVALUATION.md", "Simulated. SYNTHETIC numbers from seeded software models."),
        "evaluation-r2.html": md_page("evaluation-r2.html", "Evaluation, second round", "docs/EVALUATION_R2.md", "Simulated. SYNTHETIC numbers from seeded software models."),
        "limitations.html": md_page("limitations.html", "Limitations", "docs/LIMITATIONS.md", "What the work does not show."),
        "fetch.html": md_page("fetch.html", "Fetch list", "docs/FETCH_LIST.md", "Open: items that could not be retrieved, for the owner to fetch by hand."),
        "ar.html": arabic_page(f),
    }


def main(argv=None) -> int:
    out = (argv or sys.argv[1:] or ["site"])[0]
    os.makedirs(out, exist_ok=True)
    for name, text in build_site().items():
        with open(os.path.join(out, name), "w", encoding="utf-8", newline="\n") as fh: fh.write(text)
        print("wrote", os.path.join(out, name))
    return 0


if __name__ == "__main__":
    sys.exit(main())
