def evidence_page(f: dict) -> str:
    rows = _csv("data/evidence_table.csv")
    fams = sorted({r["family"] for r in rows}); binds = ["mandatory", "conditional", "voluntary", "guidance"]
    acc = ["full text seen", "summary seen", "title only"]
    opt = lambda vals: '<option value="">all</option>' + "".join(f'<option value="{html.escape(v)}">{html.escape(v)}</option>' for v in vals)
    trs = "".join(
        f'<tr data-family="{html.escape(r["family"])}" data-binding="{r["binding_status"]}" data-access="{r["access_level"]}">'
        f'<td>{r["id"]}</td><td>{html.escape(r["family"])}</td><td>{html.escape(r["instrument"])}</td><td>{r["binding_status"]}</td>'
        f'<td>{r["access_level"]}</td><td>{html.escape(r["requirement_paraphrase"])}</td>'
        f'<td><a href="{html.escape(r["source_url"])}" rel="noreferrer">source</a> ({r["retrieval_date"]})</td></tr>' for r in rows)
    body = f"""<p>Documented rows: short paraphrases of retrieved sources, never source text. Access level records what the reader saw.
Rows are leads to confirm in the source; the verification error rates are in the report (section 2.3).</p>
<div class="filters" role="search"><label>Family<select id="f-family">{opt(fams)}</select></label>
<label>Binding status<select id="f-binding">{opt(binds)}</select></label><label>Access level<select id="f-access">{opt(acc)}</select></label>
<label>Text<input id="f-text" type="search" placeholder="filter text"></label><p id="count" aria-live="polite">{len(rows)} of {len(rows)} rows</p></div>
<div class="table-wrap"><table id="rows"><thead><tr><th>Id</th><th>Family</th><th>Instrument</th><th>Binding</th><th>Access</th><th>Paraphrase</th><th>Source</th></tr></thead>
<tbody>{trs}</tbody></table></div>"""
    script = """const q=s=>document.getElementById(s);const rows=[...document.querySelectorAll('#rows tbody tr')];
function apply(){const fa=q('f-family').value,b=q('f-binding').value,a=q('f-access').value,t=q('f-text').value.toLowerCase();let n=0;
rows.forEach(r=>{const ok=(!fa||r.dataset.family===fa)&&(!b||r.dataset.binding===b)&&(!a||r.dataset.access===a)&&(!t||r.textContent.toLowerCase().includes(t));
r.hidden=!ok;if(ok)n++});q('count').textContent=n+' of '+rows.length+' rows'}
['f-family','f-binding','f-access','f-text'].forEach(i=>q(i).addEventListener('input',apply));"""
    return page("evidence.html", "Evidence table", body, script=script)


def coverage_page(f: dict) -> str:
    rows = list(csv.reader(open(os.path.join(ROOT, "data/coverage_matrix.csv"), encoding="utf-8", newline="")))
    head = "".join(f"<th>{html.escape(c)}</th>" for c in rows[0])
    body_rows = "".join("<tr>" + "".join(f"<td>{html.escape(c)}</td>" for c in r) + "</tr>" for r in rows[1:])
    body = f"""<p>Interpreted: instrument families (our grouping) against evidence types (our taxonomy). Each cell shows the strongest
binding status among the family's rows for that type: M mandatory, C conditional, V voluntary, G guidance, empty none.</p>
<div class="table-wrap"><table><thead><tr>{head}</tr></thead><tbody>{body_rows}</tbody></table></div>"""
    return page("coverage.html", "Coverage matrix", body)


def case_page(f: dict) -> str:
    case = yaml.safe_load(open(os.path.join(ROOT, "assurance/library_robot_case.yaml"), encoding="utf-8"))
    svg = open(os.path.join(ROOT, "figures/gsn_library_robot.svg"), encoding="utf-8").read()
    svg = svg[svg.index("<svg"):]
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    info = {}
    for g in case["goals"]:
        info[g["id"]] = {"kind": "goal", "text": g["text"], "about": g.get("claim_about"), "evidence": g.get("evidence", [])}
    for e in case["evidence"]:
        info["SN_" + e["id"].replace("-", "")] = {"kind": "evidence", "id": e["id"], "text": e["title"], "status": e["status"],
                                                 "evidence_kind": e.get("kind", ""), "artefact": e.get("artefact", ""), "rows": e["rows"], "note": e.get("note", "")}
    trs = "".join(f'<tr><td>{e["id"]}</td><td>{html.escape(e["title"])}</td><td><span class="chip">{e["status"]}</span></td>'
                  f'<td>{e.get("kind", "")}</td><td>{", ".join(e["rows"])}</td></tr>' for e in case["evidence"])
    body = f"""<p>Proposal: an assurance case skeleton for an assumed library service robot. Select a goal or an evidence circle in the
diagram to see its status; the table below gives the same information without the diagram. {f['N_OPEN']} of {f['N_EVIDENCE_ITEMS']} items are open and
{f['N_PARTIAL']} are partial with simulated evidence only.</p>
<div class="svgbox" role="group" aria-label="Assurance case diagram">{svg}</div>
<div id="details" role="status" aria-live="polite">Select a node to see its details.</div>
<h2>Evidence items</h2><div class="table-wrap"><table><thead><tr><th>Item</th><th>Title</th><th>Status</th><th>Kind</th><th>Table rows</th></tr></thead><tbody>{trs}</tbody></table></div>"""
    script = ("const info=" + json.dumps(info, sort_keys=True, ensure_ascii=False) + ";" + """
const box=document.getElementById('details');const esc=s=>String(s).replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
document.querySelectorAll('.svgbox g.node').forEach(n=>{const id=(n.querySelector('title')||{}).textContent;if(!info[id])return;
n.setAttribute('tabindex','0');n.setAttribute('role','button');
const show=()=>{const d=info[id];box.innerHTML=d.kind==='goal'?'<strong>'+esc(id)+'</strong> (claim about '+esc(d.about)+'): '+esc(d.text)+'<br>Evidence: '+esc(d.evidence.join(', ')||'through the strategy')
:'<strong>'+esc(d.id)+'</strong>: '+esc(d.text)+'<br>Status: '+esc(d.status)+(d.evidence_kind?' ('+esc(d.evidence_kind)+')':'')+(d.artefact?'<br>Artefact: <code>'+esc(d.artefact)+'</code>':'')+'<br>Table rows: '+esc(d.rows.join(', '))+(d.note?'<br>'+esc(d.note):'')};
n.addEventListener('click',show);n.addEventListener('keydown',e=>{if(e.key==='Enter'||e.key===' '){e.preventDefault();show()}})});""")
    return page("case.html", "Assurance case", body, script=script)


def md_page(name: str, title: str, rel: str, lead: str) -> str:
    return page(name, title, f"<p><em>{html.escape(lead)}</em></p>" + _md(rel))


