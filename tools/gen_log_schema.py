#!/usr/bin/env python3
"""Generate JSON schemas for the pilot kit log files from data/pilot_streams.csv and data/pilot_log_spec.csv.

Usage: python tools/gen_log_schema.py           write docs/PILOT_KIT/schemas/<stream>.schema.json
       python tools/gen_log_schema.py --check   exit 1 if a committed schema is stale
Layer: tools. Standard library only. A schema describes one CSV row as an object. Rates are "assumed, proposal".
"""
from __future__ import annotations

import argparse, csv, json, os, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "docs", "PILOT_KIT", "schemas")
TYPES = {"number": {"type": "number"}, "integer": {"type": "integer"}, "text": {"type": "string"}}


def load() -> tuple[list[dict], list[dict]]:
    rd = lambda rel: list(csv.DictReader(open(os.path.join(ROOT, rel), encoding="utf-8", newline="")))
    return rd("data/pilot_streams.csv"), rd("data/pilot_log_spec.csv")


def schemas() -> dict[str, str]:
    streams, cols = load()
    out = {}
    for s in streams:
        mine = [c for c in cols if c["stream"] == s["stream"]]
        props = {c["column"]: TYPES[c["type"]] | {"description": f'{c["description"]} ({c["unit"]})'} for c in mine}
        if "fix_ok" in props or "slow_command" in props or "shade" in props:
            for k in ("fix_ok", "slow_command", "shade"):
                if k in props: props[k]["enum"] = [0, 1]
        doc = {"$schema": "https://json-schema.org/draft/2020-12/schema",
               "$comment": "Generated by tools/gen_log_schema.py from data/pilot_streams.csv and data/pilot_log_spec.csv. Do not edit by hand.",
               "title": f'{s["file"]}: one row', "description": s["purpose"], "type": "object", "properties": props,
               "required": [c["column"] for c in mine if c["required"] == "yes"],
               "x-file": s["file"], "x-min-rate-hz": float(s["min_rate_hz"]), "x-rate-provenance": s["provenance"],
               "x-column-order": [c["column"] for c in mine]}
        out[f'{s["stream"]}.schema.json'] = json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    return out


def stale() -> list[str]:
    bad = []
    for name, text in schemas().items():
        p = os.path.join(OUT, name)
        if not os.path.exists(p) or open(p, encoding="utf-8", newline="").read() != text: bad.append(name)
    return bad


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(); ap.add_argument("--check", action="store_true"); a = ap.parse_args(argv)
    if a.check:
        s = stale()
        for n in s: print("STALE", n)
        print(f"{len(s)} stale log schemas"); return 1 if s else 0
    os.makedirs(OUT, exist_ok=True)
    for name, text in schemas().items():
        with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as f: f.write(text)
        print("wrote", name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
