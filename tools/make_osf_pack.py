#!/usr/bin/env python3
"""Build the registration pack for the public preregistration of round 3, and the archive metadata.

Layer: tools. Standard library only. No account is created and nothing is uploaded.

    python tools/make_osf_pack.py     writes docs/OSF_REGISTRATION.md and .zenodo.json

The pack maps docs/PREREG_R3_DRAFT.md onto the headings of the public registry form (section 7 of the draft) and records the
SHA-256 of the draft, so that the registered text can be compared with the committed one. Bracketed items in the draft are listed:
they must be filled, committed, and the hash re-recorded before registration. The two lines the round 3 runner reads
(`Registration identifier:` and `AC-N4 limit per hour:`) are left as placeholders for the owner.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
DRAFT = os.path.join(ROOT, "docs", "PREREG_R3_DRAFT.md")
RQ = os.path.join(ROOT, "docs", "RESEARCH_QUESTION.md")
OUT = os.path.join(ROOT, "docs", "OSF_REGISTRATION.md")
ZENODO = os.path.join(ROOT, ".zenodo.json")


def sections(text: str) -> dict[str, str]:
    """Second level sections of the draft, keyed by their number (for example '4')."""
    out, key, buf = {}, None, []
    for line in text.splitlines():
        m = re.match(r"^## (\d+)\.", line)
        if m:
            if key: out[key] = "\n".join(buf).strip()
            key, buf = m.group(1), [line]
        elif key:
            buf.append(line)
    if key: out[key] = "\n".join(buf).strip()
    return out


def brackets(text: str) -> list[str]:
    """Outermost bracketed to-do items, whole (nested brackets included); citation style links with a following parenthesis are skipped."""
    items, depth, start = [], 0, 0
    for k, ch in enumerate(text):
        if ch == "[":
            if depth == 0: start = k
            depth += 1
        elif ch == "]" and depth:
            depth -= 1
            if depth == 0 and text[k + 1:k + 2] != "(":
                body = " ".join(text[start + 1:k].split())
                if len(body) > 2: items.append(body if len(body) <= 160 else body[:157] + "...")
    return items


def hypotheses(rq_text: str) -> str:
    rows = [l for l in rq_text.splitlines() if re.match(r"^\| H[345] ", l)]
    return "\n".join(rows)


def build(draft: str, rq_text: str) -> str:
    sha = hashlib.sha256(draft.encode("utf-8")).hexdigest()
    s = sections(draft)
    todo = brackets(draft)
    out = ["# Round 3 preregistration pack", "",
           "Generated by `tools/make_osf_pack.py`. Do not edit by hand. Nothing here has been registered or uploaded.", "",
           "Registration identifier: [to be entered by the owner after registration]",
           "AC-N4 limit per hour: [to be entered before registration; set from the synthetic arm's false alarm rate, as the draft says]", "",
           f"Draft file: `docs/PREREG_R3_DRAFT.md`, SHA-256 `{sha}`.", "",
           "Order of use: fill the bracketed items below in the draft, commit it, run this tool again so that the hash above is the hash of the final text, "
           "register that text on the public registry, then enter the identifier above. No recorded log may be replayed before the identifier is entered.", "",
           f"## Bracketed items still to fill ({len(todo)})", ""] + [f"{i}. {t}" for i, t in enumerate(todo, 1)] + [""]
    out += ["## Study information", "", "Title: Do synthetic fault generators and recorded GNSS interference give the same verdicts for the same integrity monitor? Round 3 of the dhamaan study.", "",
            "Description and hypotheses (H3 to H5 of `docs/RESEARCH_QUESTION.md`):", "", "| Id | Hypothesis | Data and test | What would falsify it |", "|---|---|---|---|", hypotheses(rq_text), ""]
    out += ["## Design plan", "", "Study type: computational, replay of existing data. Blinding: none; scripts score. Randomisation: a seeded split of recordings, drawn before any metric is computed.", "",
            s.get("1", ""), "", s.get("4", "").split("### Data")[0].strip(), ""]
    out += ["## Sampling plan", "", "Existing data: recorded logs, listed in `data/third_party_manifest.csv` with licence text. Sample size, rationale and stopping rule:", "",
            "### Data" + (s.get("4", "").split("### Data")[1].split("### Monitor")[0] if "### Data" in s.get("4", "") else ""), "", s.get("6", ""), ""]
    out += ["## Variables", "", "Manipulated: the arm (S0, S1, R) and, in Parts A and B, the mutant. Measured and indices:", "",
            "### Monitor" + (s.get("4", "").split("### Monitor")[1].split("### Predictions")[0] if "### Monitor" in s.get("4", "") else ""), ""]
    out += ["## Analysis plan", "", s.get("2", ""), "", s.get("3", ""), "", "### Predictions" + (s.get("4", "").split("### Predictions")[1] if "### Predictions" in s.get("4", "") else ""), "", s.get("5", ""), ""]
    out += ["## Other", "", "The monitor and thresholds are those of rounds 1 and 2 at the code hash recorded at scoring. Rounds 1 and 2 are frozen. Deviations are logged in `sim/DEVIATIONS.md`. All simulated outputs are SYNTHETIC.", ""]
    return "\n".join(out)


def zenodo() -> dict:
    return {"title": "dhamaan: source traced safety evidence, a checkable assurance case and preregistered simulation for robots and drones in Gulf conditions",
            "upload_type": "software",
            "description": "A source traced evidence table of robot and drone safety instruments, a machine checkable assurance case with a credit ledger, preregistered seeded simulations whose outputs are labelled synthetic, a local command line tool and a pilot kit. Student proposal seed. Not certification and not endorsed by any body.",
            "creators": [{"name": "Mueen, Huda"}],
            "license": "cc-by-4.0",
            "keywords": ["assurance case", "safety case", "robotics", "drones", "GNSS", "preregistration", "simulation credibility"],
            "access_right": "open",
            "notes": "The licence is proposed until the owner confirms it (LICENSES.md)."}


def main() -> int:
    draft = open(DRAFT, encoding="utf-8").read()
    rq_text = open(RQ, encoding="utf-8").read()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(build(draft, rq_text))
    with open(ZENODO, "w", encoding="utf-8", newline="\n") as f:
        json.dump(zenodo(), f, indent=2, ensure_ascii=False)
        f.write("\n")
    print("wrote", os.path.relpath(OUT, ROOT), "and", os.path.relpath(ZENODO, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
