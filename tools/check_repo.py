#!/usr/bin/env python3
"""Repository guard: fail if standard text, paywalled PDFs or unlicensed raw downloads are committed.
Heuristics only. A pass is not proof of compliance; see LICENSES.md and README.md. Standard library only."""
from __future__ import annotations
import os, re, sys, csv, argparse

ALLOWED_EXT = {".md",".csv",".json",".yaml",".yml",".py",".txt",".dot",".svg",".toml",".cfg",".ini",".gitignore",""}
IMAGE_EXT = {".png",".svg"}              # only under figures/
FORBIDDEN_EXT = {".pdf",".epub",".docx",".doc",".xlsx",".pptx",".zip",".tar",".gz",".tgz",".7z",".rar",
                 ".html",".htm",".xml",".mhtml",".warc",".mobi",".djvu"}
RAW_DIRS = {"raw","raw_downloads","downloads","download","cache","fulltext","full_text","standards_text","pdfs","mirror","mirrors","scraped"}
MAX_BYTES = 1_500_000
NOSCAN = ("tools/check_repo.py","tests/")   # files that contain marker strings by design
MARKERS = [
    (r"©\s*(ISO|IEC|ANSI|IEEE|UL|BSI|CEN|CENELEC|SAE)\b", "copyright notice of a standards body"),
    (r"\bCopyright\s*(©|\(c\))?\s*(ISO|IEC|ANSI|IEEE|UL LLC|BSI|CEN|SAE)\b", "copyright notice of a standards body"),
    (r"licen[cs]ed to\b.{0,60}\b(ISO|IEC|BSI|ANSI)", "licensed copy watermark"),
    (r"this document is a preview generated by", "standards preview watermark"),
    (r"no part of this (publication|document) may be reproduced", "publisher reproduction notice"),
    (r"single user licen[cs]e", "single user licence watermark"),
    (r"reproduction or networking permitted without license", "licence watermark"),
    (r"\bINTERNATIONAL STANDARD\s+ISO(/IEC)?\s*\d{3,5}.{0,40}Reference number", "standard cover page"),
]
QUOTE = re.compile(r"(?:(?<=^)|(?<=[\s(\[]))[\"“](?=\S)([^\"”\n]{40,}?)(?<=\S)[\"”](?=[\s.,;:)\]!?]|$)", re.M)

def words(s): return len(s.split())

def scan(root: str, max_quote: int = 25, warn_quote: int = 15) -> tuple[list[str], list[str]]:
    """Return (errors, warnings) for the repository tree at root."""
    errors, warns = [], []
    manifest = set()
    mp = os.path.join(root, "data", "third_party_manifest.csv")
    if os.path.exists(mp):
        for r in csv.DictReader(open(mp, encoding="utf-8")):
            if r.get("licence","").strip().lower() not in ("","unknown","unconfirmed","tbd"):
                manifest.add(r["path"].strip())
    for dp, dn, fn in os.walk(root):
        dn[:] = [d for d in dn if d not in (".git",".github_cache","__pycache__",".pytest_cache","node_modules")]
        rel_dir = os.path.relpath(dp, root).replace(os.sep, "/")
        for d in list(dn):
            if d.lower() in RAW_DIRS or d.lower().startswith("raw_"):
                errors.append(f"{rel_dir}/{d}: raw download directory name not allowed")
        for f in fn:
            p = os.path.join(dp, f); rel = os.path.relpath(p, root).replace(os.sep, "/")
            ext = os.path.splitext(f)[1].lower()
            size = os.path.getsize(p)
            if ext in FORBIDDEN_EXT: errors.append(f"{rel}: forbidden file type {ext} (PDFs and raw downloads are not committed)"); continue
            if ext in IMAGE_EXT and not rel.startswith("figures/") and not rel.startswith("docs/figures/"):
                errors.append(f"{rel}: image outside figures/"); continue
            if ext not in ALLOWED_EXT and ext not in IMAGE_EXT: errors.append(f"{rel}: file type {ext!r} not on allowlist"); continue
            if size > MAX_BYTES: errors.append(f"{rel}: {size} bytes exceeds {MAX_BYTES}")
            if rel.startswith("third_party/") and rel not in manifest:
                errors.append(f"{rel}: third party file without a confirmed licence in data/third_party_manifest.csv")
            if ext in IMAGE_EXT or any(rel.startswith(n) or rel == n for n in NOSCAN): continue
            try: text = open(p, encoding="utf-8").read()
            except UnicodeDecodeError: errors.append(f"{rel}: not UTF-8 text"); continue
            if text.startswith("%PDF"): errors.append(f"{rel}: PDF content")
            for pat, why in MARKERS:
                if re.search(pat, text, re.I | re.S): errors.append(f"{rel}: {why}")
            if ext not in (".md", ".txt", ".csv"): continue
            if ext == ".md" and text.startswith("---"):
                end = text.find("\n---", 3); text = text[end + 4:] if end > 0 else text
            chunks = []
            if ext == ".csv":
                try:
                    for row in csv.reader(text.splitlines()):
                        chunks.extend(row)
                except csv.Error: chunks = [text]
            else: chunks = [text]
            for ch in chunks:
                for m in QUOTE.finditer(ch):
                    n = words(m.group(1))
                    if n >= max_quote: errors.append(f"{rel}: quoted passage of {n} words (limit {max_quote - 1})")
                    elif n >= warn_quote: warns.append(f"{rel}: quoted passage of {n} words (protocol asks for under 15)")
    return errors, warns

if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("root", nargs="?", default=".")
    a = ap.parse_args(); e, w = scan(a.root)
    for x in w: print("WARN", x)
    for x in e: print("ERROR", x)
    print(f"{len(e)} errors, {len(w)} warnings"); sys.exit(1 if e else 0)
