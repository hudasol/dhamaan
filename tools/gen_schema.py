#!/usr/bin/env python3
"""Generate JSON schemas in schema/ from the typed contracts in tools/contracts.py.

Usage: python tools/gen_schema.py           write the schema files
       python tools/gen_schema.py --check   exit 1 if a committed schema file is stale
Layer: tools. Standard library only. Output is deterministic (sorted keys, LF endings).
"""
from __future__ import annotations

import argparse, json, os, sys

import contracts as ct

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
HEADER = "Generated by tools/gen_schema.py from tools/contracts.py. Do not edit by hand."


def evidence_table_schema() -> dict:
    props = {}
    for c in ct.EVIDENCE_TABLE:
        p: dict = {"type": "string", "description": c.description}
        if c.enum: p["enum"] = list(c.enum)
        if c.pattern: p["pattern"] = c.pattern
        if c.non_empty and not c.enum and not c.pattern: p["minLength"] = 1
        props[c.name] = p
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", "$comment": HEADER,
            "title": "Evidence table row (data/evidence_table.csv)", "type": "object",
            "properties": props, "required": [c.name for c in ct.EVIDENCE_TABLE],
            "additionalProperties": False, "x-column-order": [c.name for c in ct.EVIDENCE_TABLE]}


def _field(f: ct.Field) -> dict:
    if f.kind == "ids": p: dict = {"type": "array", "items": {"type": "string"}}
    elif f.kind == "boolean": p = {"type": "boolean"}
    else: p = {"type": "string"}
    p["description"] = f.description
    if f.enum: p["enum"] = list(f.enum)
    if f.pattern: p["pattern"] = f.pattern
    return p


def case_schema() -> dict:
    defs, props = {}, {}
    for k in ct.CASE:
        defs[k.key] = {"type": "object", "description": k.description,
                       "properties": {f.name: _field(f) for f in k.fields},
                       "required": [f.name for f in k.fields if f.required], "additionalProperties": False}
        props[k.key] = {"type": "array", "items": {"$ref": f"#/$defs/{k.key}"}}
    props["meta"] = {"type": "object", "properties": {m: {"type": "string"} for m in ct.META_FIELDS},
                     "additionalProperties": False}
    props["strategy_links"] = {"type": "object", "additionalProperties": {"type": "array", "items": {"type": "string"}}}
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", "$comment": HEADER,
            "title": "Assurance case (assurance/*.yaml)", "type": "object", "properties": props,
            "additionalProperties": False, "$defs": defs}


OUTPUTS = {"schema/evidence_table.schema.json": evidence_table_schema,
           "schema/assurance_case.schema.json": case_schema}


def render(fn) -> str:
    return json.dumps(fn(), indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def stale() -> list[str]:
    """Paths whose committed content differs from what the contracts generate."""
    out = []
    for rel, fn in OUTPUTS.items():
        p = os.path.join(ROOT, rel)
        if not os.path.exists(p) or open(p, encoding="utf-8", newline="").read() != render(fn): out.append(rel)
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(); ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    if a.check:
        s = stale()
        for rel in s: print("STALE", rel)
        print(f"{len(s)} stale schema files"); return 1 if s else 0
    for rel, fn in OUTPUTS.items():
        p = os.path.join(ROOT, rel); os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as f: f.write(render(fn))
        print("wrote", rel)
    return 0


if __name__ == "__main__":
    sys.exit(main())
