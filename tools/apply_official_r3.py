#!/usr/bin/env python3
"""Merge the round 3 official checks into a new status file, without touching data/official_checks.csv.

Layer: tools. Standard library only.

    python tools/apply_official_r3.py          writes data/official_r3_status.csv

Input : data/official_checks.csv (frozen), data/official_r3/*.csv (one row per check id, with a new status)
Output: data/official_r3_status.csv, all 71 original checks, with status_before, status_after and a basis column.
Rules : a check id that has no round 3 row keeps its status; a round 3 row replaces status and value; items that
        stay open stay open. Every round 3 value rests on a machine written extraction of the official text, not on the page
        as printed, so basis says so and hand_check_needed is yes until the owner reads the cited page.
"""
from __future__ import annotations

import csv
import glob
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
BASE = os.path.join(ROOT, "data", "official_checks.csv")
R3 = os.path.join(ROOT, "data", "official_r3")
OUT = os.path.join(ROOT, "data", "official_r3_status.csv")
FETCH = os.path.join(ROOT, "docs", "FETCH_LIST_R3.md")
BASIS = "machine written extraction of the official text, not read as printed"
STATUSES = {"confirmed", "open", "not_accessible", "conflict"}


def read(path: str) -> list[dict]:
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def merge(base: list[dict], updates: list[dict]) -> list[dict]:
    seen = {}
    for u in updates:
        if u["new_status"] not in STATUSES:
            raise ValueError(f"{u['check_id']}: status {u['new_status']!r}")
        if u["check_id"] in seen:
            raise ValueError(f"{u['check_id']}: two round 3 rows")
        seen[u["check_id"]] = u
    unknown = set(seen) - {b["check_id"] for b in base}
    if unknown:
        raise ValueError(f"round 3 rows for unknown checks: {sorted(unknown)}")
    out = []
    for b in base:
        r = dict(b)
        r["status_before"] = b["status"]
        u = seen.get(b["check_id"])
        if u:
            r.update(status=u["new_status"], value=u["value"] or b["value"], locator_seen=u["locator"] or b["locator_seen"],
                     source_url=u["source_url"] or b["source_url"], source_type=u["source_type"] or b["source_type"],
                     access_seen=u["access"] or b["access_seen"], retrieved_on=u["retrieved_on"] or b["retrieved_on"],
                     conflicts=u["conflicts"] or b["conflicts"])
            r["basis"] = BASIS
            r["hand_check_needed"] = "yes"
            r["hand_fetch_url_and_page"] = u["hand_fetch_url_and_page"]
        else:
            r["basis"] = "round 2 checks, unchanged"
            r["hand_check_needed"] = "yes" if b["status"] != "confirmed" else "no"
            r["hand_fetch_url_and_page"] = b.get("download_if_blocked", "")
        r["status_after"] = r["status"]
        out.append(r)
    return out


DATA_STEPS = (
    "Open the Yunnan University GNSS interference data set on the Mendeley data service and find Part III (jamming and spoofing, 21 December 2023). The Part I record lists no files and states no licence, so record the licence from the page before any use.",
    "Open the page of the Jammertest 2024 vehicular paper and find whether any data are released and under which licence. The page could not be retrieved by the automated service.",
    "Open the data page of the Finnish Geospatial Institute jammer test and read the licence statement. The data are raw samples, so a software receiver would be needed to produce position fixes.",
    "Read the terms of service of the PX4 flight log service. Logs are kept for 12 months, so download any log needed before it is deleted.",
    "Record every chosen data set, its licence text and its URL in data/third_party_manifest.csv before any replay.",
)


def where(r: dict) -> str:
    h = r["hand_fetch_url_and_page"].strip()
    return r["source_url"] if not h or h.lower().startswith("none") else h


def fetch_list(rows: list[dict]) -> str:
    """Markdown list of what the owner reads by hand, built from the status file."""
    todo = [r for r in rows if r["basis"] == BASIS and r["hand_check_needed"] == "yes"]
    still = [r for r in rows if r["status_after"] in ("open", "not_accessible") and r["basis"] != BASIS]
    out = ["# Hand fetch list, round 3", "",
           "Generated by `tools/apply_official_r3.py` from `data/official_r3_status.csv`. Do not edit by hand.", "",
           "Every value below was read through a service that returns a machine written extraction of the official text. None was read as printed. "
           "Read the cited page yourself, then record the result in a new row; never commit standard or regulation text.", "",
           f"## A. Round 3 values to check against the printed page ({len(todo)})", "",
           "| Check | Item | Status now | Where to read |", "|---|---|---|---|"]
    for r in todo:
        out.append(f"| {r['check_id']} | {r['item']} | {r['status_after']} | {where(r)} |")
    out += ["", f"## B. Items still open or not accessible from earlier rounds ({len(still)})", "", "| Check | Item | Status | Where to read |", "|---|---|---|---|"]
    for r in still:
        out.append(f"| {r['check_id']} | {r['item']} | {r['status_after']} | {where(r)} |")
    out += ["", "## C. Real GNSS data, by hand", ""] + [f"{i}. {t}" for i, t in enumerate(DATA_STEPS, 1)] + [""]
    return "\n".join(out)


def main() -> int:
    base = read(BASE)
    updates = [row for f in sorted(glob.glob(os.path.join(R3, "*.csv"))) for row in read(f)]
    rows = merge(base, updates)
    fields = [*base[0].keys(), "status_before", "status_after", "basis", "hand_check_needed", "hand_fetch_url_and_page"]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        w = csv.DictWriter(f, fieldnames=fields, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    with open(FETCH, "w", encoding="utf-8", newline="\n") as f:
        f.write(fetch_list(rows))
    from collections import Counter
    print("before:", dict(Counter(r["status_before"] for r in rows)))
    print("after: ", dict(Counter(r["status_after"] for r in rows)))
    print("wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
