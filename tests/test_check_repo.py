import os, sys, tempfile
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "tools"))
import check_repo as cr

def mk(files):
    d = tempfile.mkdtemp()
    for rel, content in files.items():
        p = os.path.join(d, rel); os.makedirs(os.path.dirname(p), exist_ok=True)
        if isinstance(content, bytes): open(p, "wb").write(content)
        else: open(p, "w", encoding="utf-8").write(content)
    return d

def test_clean_repo():
    e, w = cr.scan(mk({"README.md": "hello", "data/a.csv": "a,b\n1,2\n"})); assert e == []

def test_pdf_rejected():
    e, _ = cr.scan(mk({"docs/x.pdf": b"%PDF-1.4"})); assert any("forbidden file type" in x for x in e)

def test_pdf_content_with_other_extension():
    e, _ = cr.scan(mk({"docs/x.txt": "%PDF-1.4 stuff"})); assert any("PDF content" in x for x in e)

def test_raw_directory_rejected():
    e, _ = cr.scan(mk({"raw/a.txt": "x"})); assert any("raw download directory" in x for x in e)

def test_html_download_rejected():
    e, _ = cr.scan(mk({"data/page.html": "<html></html>"})); assert any("forbidden" in x for x in e)

def test_standard_copyright_marker():
    e, _ = cr.scan(mk({"docs/n.md": "© ISO 2023 All rights reserved"})); assert any("copyright notice" in x for x in e)

def test_watermark_marker():
    e, _ = cr.scan(mk({"docs/n.md": "This document is a preview generated by EVS"})); assert e

def test_long_quote_rejected_short_quote_ok():
    long_q = '"' + " ".join(["word"] * 30) + '"'
    e, _ = cr.scan(mk({"docs/n.md": long_q})); assert any("quoted passage" in x for x in e)
    short_q = '"' + " ".join(["word"] * 8) + ' and some more text here to pass forty"'
    e, _ = cr.scan(mk({"docs/n.md": short_q})); assert e == []

def test_csv_quoting_is_not_a_quote():
    cell = " ".join(["word"] * 40)
    e, _ = cr.scan(mk({"data/a.csv": f'a\n"{cell}"\n'})); assert e == []

def test_third_party_needs_manifest():
    e, _ = cr.scan(mk({"third_party/d.csv": "a\n1\n"})); assert any("third party" in x for x in e)
    d = mk({"third_party/d.csv": "a\n1\n", "data/third_party_manifest.csv": "path,licence,source_url,note\nthird_party/d.csv,CC0-1.0,https://x,\n"})
    e, _ = cr.scan(d); assert e == []

def test_unknown_licence_in_manifest_is_not_enough():
    d = mk({"third_party/d.csv": "a\n1\n", "data/third_party_manifest.csv": "path,licence,source_url,note\nthird_party/d.csv,unknown,https://x,\n"})
    e, _ = cr.scan(d); assert any("third party" in x for x in e)

def test_oversize_file():
    e, _ = cr.scan(mk({"data/big.csv": "a" * (cr.MAX_BYTES + 10)})); assert any("exceeds" in x for x in e)

def test_png_only_in_figures():
    e, _ = cr.scan(mk({"x.png": b"\x89PNG"})); assert any("image outside" in x for x in e)
    e, _ = cr.scan(mk({"figures/x.png": b"\x89PNG"})); assert e == []

def test_this_repo_is_clean():
    e, _ = cr.scan(os.path.join(os.path.dirname(__file__), "..")); assert e == [], e[:5]
